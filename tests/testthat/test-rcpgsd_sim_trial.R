test_that("patients are generated by region, interval and group", {
  set.seed(31)
  n_acc <- rbind(c(0, 30), c(40, 50))
  pt <- .rcpgsd_sim_trial(n_acc, c(0, 6, 18), c(0.05, 0.05), c(0.7, 0.7),
                          r = 2)
  expect_equal(as.vector(table(pt$region)), c(30, 90))
  # Region 1 enters only during the second interval
  expect_true(all(pt$entry[pt$region == 1] >= 6))
  expect_true(all(pt$entry <= 18))
  expect_equal(sum(pt$region == 2 & pt$entry < 6), 40)
  # Allocation ratio 2:1 within each region
  expect_equal(sum(pt$trt[pt$region == 1]), 20)
  expect_equal(sum(pt$trt[pt$region == 2]), 60)
  expect_true(all(pt$t_event > 0))
})

test_that("event times follow the specified hazards", {
  set.seed(32)
  n_acc <- matrix(c(20000, 20000), ncol = 1)
  pt <- .rcpgsd_sim_trial(n_acc, c(0, 1), c(0.1, 0.2), c(0.5, 1), r = 1)
  rate <- function(s, a) {
    1 / mean(pt$t_event[pt$region == s & pt$trt == a])
  }
  expect_equal(rate(1, 0), 0.10, tolerance = 0.03)
  expect_equal(rate(1, 1), 0.05, tolerance = 0.03)
  expect_equal(rate(2, 0), 0.20, tolerance = 0.03)
  expect_equal(rate(2, 1), 0.20, tolerance = 0.03)
})
